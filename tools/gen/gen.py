def splice(text, name, body, path):
    pat = re.compile(rf"(<!-- GENERATED:{name} -->\n).*?(<!-- /GENERATED:{name} -->)", re.S)
    if not pat.search(text):
        raise SpecError(f"{path}: missing <!-- GENERATED:{name} --> markers")
    note = f"<!-- {HEADER} Edit spec/tripwire.yaml. -->\n"
    return pat.sub(lambda m: m.group(1) + note + body + "\n" + m.group(2), text)


def outputs(s):
    out = {"tools/tripwire_spec.py": gen_python(s), "src/trw_defs.vh": gen_verilog(s)}
    tables = gen_tables(s)
    for path, names in DOC_TABLES.items():
        text = (ROOT / path).read_text()
        for n in names:
            text = splice(text, n, tables[n], path)
        out[path] = text
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if any output is out of date")
    args = ap.parse_args()
    try:
        spec = yaml.safe_load(SPEC.read_text())
        validate(spec)
        outs = outputs(spec)
    except SpecError as e:
        print(f"spec error: {e}", file=sys.stderr)
        return 2
    stale = []
    for rel, content in outs.items():
        path = ROOT / rel
        old = path.read_text() if path.exists() else ""
        if old == content:
            continue
        stale.append(rel)
        if args.check:
            sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), content.splitlines(True),
                                                       f"a/{rel}", f"b/{rel}", n=1))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check:
        if stale:
            print(f"\nout of date: {', '.join(stale)} (run python tools/gen/gen.py)", file=sys.stderr)
            return 1
        print("gen: all outputs up to date")
    else:
        print(f"gen: wrote {len(stale)} file(s)" + (f": {', '.join(stale)}" if stale else " (all up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
