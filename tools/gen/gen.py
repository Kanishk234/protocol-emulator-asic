#!/usr/bin/env python3
"""Generate every encoding artefact from spec/tripwire.yaml (the single source).

Outputs:
  tools/tripwire_spec.py   Python tables for tripsim (and tripc later)
  src/trw_defs.vh          Verilog `define constants for the RTL
  docs/design/ISA.md, docs/design/ARCHITECTURE.md
                           tables between <!-- GENERATED:name --> and <!-- /GENERATED:name -->

Usage:
  python tools/gen/gen.py           validate the spec and write all outputs
  python tools/gen/gen.py --check   validate and fail (exit 1) if any output is out of date (CI)
"""

import argparse
import difflib
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = ROOT / "spec" / "tripwire.yaml"
HEADER = "GENERATED by tools/gen/gen.py from spec/tripwire.yaml. DO NOT EDIT."


class SpecError(Exception):
    pass


# ----------------------------------------------------------------------------- validation
def _check(cond, msg):
    if not cond:
        raise SpecError(msg)


def _unique(items, key, what):
    seen = {}
    for it in items:
        k = it[key]
        _check(k not in seen, f"{what}: duplicate {key} {k!r} ({it.get('name')} and {seen.get(k)})")
        seen[k] = it.get("name")


def _fits(value, bits, what):
    _check(0 <= value < (1 << bits), f"{what}: {value} does not fit {bits} bits")


def _tile(ranges, width, what):
    """ranges: {name: (msb, lsb)}; check no overlaps and all inside [width-1:0]."""
    used = 0
    for name, (msb, lsb) in ranges.items():
        # YAML 1.1 reads bare on/off/yes/no as booleans: field names must be quoted strings
        _check(isinstance(name, str), f"{what}: field name {name!r} is not a string (quote it in the YAML)")
        _check(0 <= lsb <= msb < width, f"{what}.{name}: [{msb}:{lsb}] outside [{width - 1}:0]")
        mask = ((1 << (msb - lsb + 1)) - 1) << lsb
        _check(not used & mask, f"{what}.{name}: overlaps another field")
        used |= mask
    return used


def validate(s):
    tok = s["token"]
    _unique(tok["tags"], "code", "token.tags")
    _unique(tok["tags"], "name", "token.tags")
    for t in tok["tags"]:
        _fits(t["code"], tok["tag_bits"], f"tag {t['name']}")

    _unique(s["ops"], "code", "ops")
    _unique(s["ops"], "name", "ops")
    op_bits = next(f["width"] for f in s["slot"]["fields"] if f["name"] == "OP")
    _check(len(s["ops"]) == 1 << op_bits, f"ops: {len(s['ops'])} entries for a {op_bits}-bit OP field")
    for o in s["ops"]:
        _fits(o["code"], op_bits, f"op {o['name']}")

    sl = s["slot"]
    _unique(sl["fields"], "name", "slot.fields")
    ranges = {f["name"]: (f["lsb"] + f["width"] - 1, f["lsb"]) for f in sl["fields"]}
    used = _tile(ranges, sl["bits"], "slot")
    _check(used == (1 << sl["bits"]) - 1, "slot: fields leave unused bits")
    _check(sl["bits"] <= 16 * sl["host_words"], "slot: does not fit its host words")
    widths = {f["name"]: f["width"] for f in sl["fields"]}
    for enum, values in sl["enums"].items():
        _check(enum in widths, f"slot.enums.{enum}: no field of that name")
        _check(len(set(values.values())) == len(values), f"slot.enums.{enum}: duplicate codes")
        for k, v in values.items():
            _fits(v, widths[enum], f"slot.enums.{enum}.{k}")

    rt = s["routine"]
    _tile({k: tuple(v) for k, v in rt["alu"]["fields"].items()}, 15, "routine.alu")
    sub_msb, sub_lsb = rt["ctrl"]["sub"]
    _unique(rt["ctrl"]["formats"], "code", "routine.ctrl.formats")
    _unique(rt["ctrl"]["formats"], "name", "routine.ctrl.formats")
    for f in rt["ctrl"]["formats"]:
        _fits(f["code"], sub_msb - sub_lsb + 1, f"routine sub {f['name']}")
        _tile({k: tuple(v) for k, v in f["fields"].items()}, sub_lsb, f"routine.{f['name']}")
        for k in f.get("signed", ()):
            _check(k in f["fields"], f"routine.{f['name']}: signed field {k!r} does not exist")
    for enum in ("BR_COND", "SYS"):
        vals = rt["enums"][enum]
        _check(len(set(vals.values())) == len(vals), f"routine.enums.{enum}: duplicate codes")
    _check(set(rt["sys_desc"]) == set(rt["enums"]["SYS"]), "routine.sys_desc must describe every SYS kind")

    groups, used = s["pads"]["groups"], set()
    for g in groups:
        span = set(range(g["base"], g["base"] + g["count"]))
        _check(not span & used, f"pads: group {g['name']} overlaps another group")
        used |= span
    names = {f"{g['name']}{i}" for g in groups for i in range(g["count"])}
    for h in s["pads"]["host"]:
        _check(h in names, f"pads.host: unknown pad {h!r}")

    fab = s["fabric"]
    for port, srcs in legal_sources(fab).items():
        _check(0 < len(srcs) <= 1 << fab["sel_bits"], f"fabric: {port} has {len(srcs)} sources for {fab['sel_bits']} sel bits")
        _check(len(set(srcs)) == len(srcs), f"fabric: {port} lists a source twice")

    pc = s["pin_config"]
    _unique(pc["fields"], "name", "pin_config.fields")
    used = 0
    for f in pc["fields"]:
        name, bit, w = f["name"], f["bit"], f["width"]
        _check(f["kind"] in PIN_KINDS, f"pin_config.{name}: unknown kind {f['kind']!r}")
        _check(bit + w <= 16 * pc["stride"], f"pin_config.{name}: outside the unit's block")
        _check(w <= 16 - bit % 16 or bit % 16 == 0, f"pin_config.{name}: a field wider than its word must start a word")
        span = ((1 << w) - 1) << bit
        _check(not used & span, f"pin_config.{name}: overlaps another field")
        used |= span
        if f["kind"] == "enum":
            vals = f["values"]
            _check(len(set(vals.values())) == len(vals), f"pin_config.{name}: duplicate codes")
            for k, v in vals.items():
                _fits(v, w, f"pin_config.{name}.{k}")
        if f["kind"] == "pad":
            _check(w == 5, f"pin_config.{name}: pads are 5 bits (31 = none)")
    _check(pc["base"] + 6 * pc["stride"] <= pc["owner_base"], "pin_config: unit blocks overlap the owner registers")
    _check(pc["storage"] in ("latch", "flop"), "pin_config.storage must be latch or flop")
    _check(isinstance(pc["readable"], bool), "pin_config.readable must be true or false")
    fields = {f["name"]: f for f in pc["fields"]}
    owned = set()
    for feat, spec in pc["features"].items():
        for name in spec["fields"]:
            _check(name in fields, f"pin_config.features.{feat}: unknown field {name!r}")
            _check(name not in owned, f"pin_config.features.{feat}: {name} is in two features")
            owned.add(name)
        for field, modes in spec["modes"].items():
            _check(field in fields and fields[field]["kind"] == "enum",
                   f"pin_config.features.{feat}: {field} is not an enum field")
            for m in modes:
                _check(m in fields[field]["values"], f"pin_config.features.{feat}: unknown {field} {m!r}")
    _check(len(pc["units"]) == s["fabric"]["units"], "pin_config.units: one entry per pin unit")
    for u, feats in enumerate(pc["units"]):
        for feat in feats:
            _check(feat in pc["features"], f"pin_config.units[{u}]: unknown feature {feat!r}")

    _unique(s["pin_commands"], "code", "pin_commands")
    _unique(s["pin_commands"], "name", "pin_commands")
    for c in s["pin_commands"]:
        _check(1 <= c["code"] <= 15, f"pin command {c['name']}: code must be 1..15")


PIN_KINDS = {"bool", "uint", "m1", "pad", "enum", "q8", "sofs"}


def pin_cfg_masks(pc):
    """Bit masks over a unit's block: {'core': m, <feature>: m, ...}, and the used length in words.

    A field not named by any feature is core (every unit stores it, D-040)."""
    span = lambda f: ((1 << f["width"]) - 1) << f["bit"]
    owner = {n: feat for feat, spec in pc["features"].items() for n in spec["fields"]}
    masks = {"core": 0, **{feat: 0 for feat in pc["features"]}}
    for f in pc["fields"]:
        masks[owner.get(f["name"], "core")] |= span(f)
    words = max((f["bit"] + f["width"] + 15) // 16 for f in pc["fields"])
    return masks, words


def legal_sources(fab):
    """Expand the fabric patterns into {consumer port: (source, ...)} in sel order."""
    lanes, units = fab["lanes"], fab["units"]

    def expand(src, k):
        m = re.fullmatch(r"L\(k([+-])1\)\.(O[01])", src)
        if m:
            return [f"L{(k + (1 if m.group(1) == '+' else -1)) % lanes}.{m.group(2)}"]
        if src.startswith("L*."):
            return [f"L{i}.{src[3:]}" for i in range(lanes)]
        if src.startswith("U*."):
            return [f"U{i}.{src[3:]}" for i in range(units)]
        _check(re.fullmatch(r"(L\d\.O[01]|U\d\.rx|HOST_IN)", src), f"fabric: bad source pattern {src!r}")
        return [src]

    out = {}
    for port, srcs in fab["sources"].items():
        if port.startswith("Lk."):
            ports = [(f"L{k}.{port[3:]}", k) for k in range(lanes)]
        elif port.startswith("Un."):
            ports = [(f"U{u}.{port[3:]}", None) for u in range(units)]
        else:
            ports = [(port, None)]
        for name, k in ports:
            _check(k is not None or not any("(k" in s for s in srcs), f"fabric: {port} uses L(k...) without a lane")
            out[name] = tuple(x for s in srcs for x in expand(s, k))
    return out


# ----------------------------------------------------------------------------- outputs
def gen_python(s):
    sl, rt = s["slot"], s["routine"]
    fmt = lambda d: "{" + ", ".join(f"{k!r}: {tuple(v) if isinstance(v, list) else v!r}" for k, v in d.items()) + "}"
    lines = [f'"""{HEADER}"""', "",
             f"VERSION = {str(s['version'])!r}", f"STATUS = {s['status']!r}", "",
             f"DATA_BITS = {s['token']['data_bits']}", f"TAG_BITS = {s['token']['tag_bits']}",
             "TAGS = " + fmt({t["name"]: t["code"] for t in s["token"]["tags"]}), "",
             "OPS = " + fmt({o["name"]: o["code"] for o in sorted(s["ops"], key=lambda o: o["code"])}), "",
             f"SLOT_BITS = {sl['bits']}", f"SLOT_HOST_WORDS = {sl['host_words']}",
             "SLOT_FIELDS = {  # name: (lsb, width)"]
    lines += [f"    {f['name']!r}: ({f['lsb']}, {f['width']})," for f in sl["fields"]]
    lines += ["}"]
    lines += [f"{name} = " + fmt(vals) for name, vals in sl["enums"].items()]
    lines += ["", f"ROUTINE_BITS = {rt['bits']}",
              f"ROUTINE_ALU_SELECT = {rt['alu']['select']}",
              "ROUTINE_ALU_FIELDS = " + fmt(rt["alu"]["fields"]) + "  # name: (msb, lsb)",
              f"ROUTINE_CTRL_SELECT = {rt['ctrl']['select']}",
              f"ROUTINE_CTRL_SUB = {tuple(rt['ctrl']['sub'])}",
              "ROUTINE_CTRL = {  # name: (sub code, {field: (msb, lsb)})"]
    lines += [f"    {f['name']!r}: ({f['code']}, {fmt(f['fields'])})," for f in rt["ctrl"]["formats"]]
    lines += ["}", "ROUTINE_SIGNED = " + fmt({f["name"]: tuple(f.get("signed", ())) for f in rt["ctrl"]["formats"]})]
    lines += [f"{name} = " + fmt(vals) for name, vals in rt["enums"].items()]
    lines += ["", "PIN_CMD = " + fmt({c["name"]: c["code"] for c in s["pin_commands"]}),
              "TX_LENTOK = " + fmt(s["tx_lentok"]), ""]
    pads = {f"{g['name']}{i}": g["base"] + i for g in s["pads"]["groups"] for i in range(g["count"])}
    lines += ["PAD_GROUPS = " + fmt({g["name"]: (g["base"], g["count"], g["dir"]) for g in s["pads"]["groups"]}),
              "PADS = " + fmt(pads),
              f"HOST_PADS = {tuple(pads[h] for h in s['pads']['host'])!r}", "",
              f"FABRIC_SEL_BITS = {s['fabric']['sel_bits']}",
              "LEGAL_SOURCES = {  # consumer port: sources in sel order (ARCHITECTURE.md §4.6)"]
    lines += [f"    {p!r}: {srcs!r}," for p, srcs in legal_sources(s["fabric"]).items()]
    lines += ["}", ""]
    pc = s["pin_config"]
    lines += [f"PIN_CFG_BASE = {pc['base']:#06x}", f"PIN_CFG_STRIDE = {pc['stride']}",
              f"PIN_OWNER_BASE = {pc['owner_base']:#06x}",
              "PIN_CFG_FIELDS = {  # name: (bit, width, kind) inside a unit's block (ARCHITECTURE.md §7.2)"]
    lines += [f"    {f['name']!r}: ({f['bit']}, {f['width']}, {f['kind']!r})," for f in pc["fields"]]
    lines += ["}", "PIN_CFG_ENUMS = {"]
    lines += [f"    {f['name']!r}: {f['values']!r}," for f in pc["fields"] if f["kind"] == "enum"]
    lines += ["}", f"PIN_CFG_STORAGE = {pc['storage']!r}", f"PIN_CFG_READABLE = {pc['readable']!r}",
              "PIN_FEATURES = {  # optional feature: (fields, {enum field: modes}) (D-040)"]
    lines += [f"    {k!r}: ({tuple(v['fields'])!r}, {({f: tuple(m) for f, m in v['modes'].items()})!r}),"
              for k, v in pc["features"].items()]
    lines += ["}", "PIN_UNIT_FEATURES = (  # U0, U1, ...: the optional features each unit has"]
    lines += [f"    {tuple(u)!r}," for u in pc["units"]]
    lines += [")", ""]
    return "\n".join(lines)


def gen_verilog(s):
    sl, rt = s["slot"], s["routine"]
    L = [f"// {HEADER}", f"// spec version {s['version']} ({s['status']})",
         "`ifndef TRW_DEFS_VH", "`define TRW_DEFS_VH", "",
         f"`define TRW_DATA_BITS {s['token']['data_bits']}",
         f"`define TRW_TAG_BITS {s['token']['tag_bits']}"]
    tb = s["token"]["tag_bits"]
    L += [f"`define TRW_TAG_{t['name']} {tb}'d{t['code']}" for t in s["token"]["tags"]]
    L += ["", "// operation table (shared by reflex slots and routines)"]
    L += [f"`define TRW_OP_{o['name']} 4'd{o['code']}" for o in sorted(s["ops"], key=lambda o: o["code"])]
    L += ["", "// reflex slot fields", f"`define TRW_SLOT_BITS {sl['bits']}"]
    for f in sl["fields"]:
        n = f["name"]
        L += [f"`define TRW_SLOT_{n}_LSB {f['lsb']}", f"`define TRW_SLOT_{n}_MSB {f['lsb'] + f['width'] - 1}",
              f"`define TRW_SLOT_{n}_W {f['width']}"]
    widths = {f["name"]: f["width"] for f in sl["fields"]}
    for enum, vals in sl["enums"].items():
        L += [f"`define TRW_{enum}_{k.upper()} {widths[enum]}'d{v}" for k, v in vals.items()]
    L += ["", "// routine words", f"`define TRW_RT_BITS {rt['bits']}"]
    for k, (msb, lsb) in rt["alu"]["fields"].items():
        L += [f"`define TRW_RT_ALU_{k.upper()}_MSB {msb}", f"`define TRW_RT_ALU_{k.upper()}_LSB {lsb}"]
    smsb, slsb = rt["ctrl"]["sub"]
    L += [f"`define TRW_RT_SUB_MSB {smsb}", f"`define TRW_RT_SUB_LSB {slsb}"]
    for f in rt["ctrl"]["formats"]:
        L += [f"`define TRW_RT_SUB_{f['name']} {smsb - slsb + 1}'d{f['code']}"]
        for k, (msb, lsb) in f["fields"].items():
            L += [f"`define TRW_RT_{f['name']}_{k.upper()}_MSB {msb}", f"`define TRW_RT_{f['name']}_{k.upper()}_LSB {lsb}"]
    L += [f"`define TRW_BR_{k.upper()} 3'd{v}" for k, v in rt["enums"]["BR_COND"].items()]
    L += [f"`define TRW_SYS_{k} 4'd{v}" for k, v in rt["enums"]["SYS"].items()]
    L += ["", "// pin-unit CTRL commands: data[15:12]"]
    L += [f"`define TRW_CMD_{c['name']} 4'd{c['code']}" for c in s["pin_commands"]]
    L += _verilog_pin_config(s)
    L += ["", "`endif", ""]
    names = [line.split()[1] for line in L if line.startswith("`define ")]
    dup = sorted({n for n in names if names.count(n) > 1})
    _check(not dup, f"generated Verilog defines collide: {', '.join(dup)}")
    return "\n".join(L)


def _verilog_pin_config(s):
    """Pin-unit configuration (ARCHITECTURE.md §7.2): field positions inside a unit's block
    (bit = 16 * word + bit in word), enum codes, and which bits each unit stores (D-040)."""
    pc = s["pin_config"]
    masks, words = pin_cfg_masks(pc)
    nbits = 16 * words
    L = ["", "// pin-unit configuration (ARCHITECTURE.md §7.2): positions inside a unit's block,",
         "// bit = 16 * word + bit in word; the block is TRW_PC_WORDS host words",
         f"`define TRW_PC_BASE 16'h{pc['base']:04x}", f"`define TRW_PC_STRIDE {pc['stride']}",
         f"`define TRW_PC_OWNER_BASE 16'h{pc['owner_base']:04x}",
         f"`define TRW_PC_WORDS {words}", f"`define TRW_PC_BITS {nbits}",
         "`define TRW_PAD_NONE 5'd31"]
    for f in pc["fields"]:
        n, b, w = f["name"].upper(), f["bit"], f["width"]
        L += [f"`define TRW_PC_{n}_LSB {b}", f"`define TRW_PC_{n}_MSB {b + w - 1}", f"`define TRW_PC_{n}_W {w}"]
        if f["kind"] == "enum":
            L += [f"`define TRW_PCE_{n}_{str(k).upper()} {w}'d{v}" for k, v in f["values"].items()]
    L += ["// bits stored per feature (a lean unit stores only CORE, D-040)"]
    L += [f"`define TRW_PC_MASK_{k.upper()} {nbits}'h{m:0{nbits // 4}x}" for k, m in masks.items()]
    L += ["// units that have each optional feature, bit u = unit u"]
    nu = len(pc["units"])
    for feat in pc["features"]:
        bits = "".join("1" if feat in pc["units"][u] else "0" for u in reversed(range(nu)))
        L += [f"`define TRW_PC_UNITS_{feat.upper()} {nu}'b{bits}"]
    return L


def _bits(msb, lsb):
    return f"[{msb}]" if msb == lsb else f"[{msb}:{lsb}]"


def gen_tables(s):
    sl, rt = s["slot"], s["routine"]
    t = {}
    rows = ["| OP | Name | Data result d | Flag result R | Used for |", "|---|---|---|---|---|"]
    rows += [f"| {o['code']} | {o['name']} | {o['d']} | {o['r']} | {o['use']} |"
             for o in sorted(s["ops"], key=lambda o: o["code"])]
    t["ops"] = rows
    rows = ["| Bits | Field | Part | Meaning |", "|---|---|---|---|"]
    for f in sorted(sl["fields"], key=lambda f: f["lsb"]):
        rows.append(f"| {_bits(f['lsb'] + f['width'] - 1, f['lsb'])} | {f['name']} | {f['group']} | {f['desc']} |")
    rows += ["", "| Enum | Codes |", "|---|---|"]
    rows += [f"| {e} | " + ", ".join(f"{v} {k}" for k, v in vals.items()) + " |" for e, vals in sl["enums"].items()]
    t["slot_fields"] = rows
    alu = rt["alu"]["fields"]
    rows = ["| Word | [15] | [14:12] | Fields | Meaning |", "|---|---|---|---|---|",
            "| ALU | 0 | (op) | " + " ".join(f"{k}{_bits(*v)}" for k, v in alu.items()) +
            " | one op from the operation table; RZ := R |"]
    for f in rt["ctrl"]["formats"]:
        fields = " ".join(f"{k}{_bits(*v)}" for k, v in f["fields"].items())
        rows.append(f"| {f['name']} | 1 | {f['code']:03b} | {fields} | {f['desc']} |")
    rows += ["", "BR conditions: " + ", ".join(f"{v} = {k}" for k, v in rt["enums"]["BR_COND"].items()) + ".",
             "", "| SYS kind | Name | Effect (arg = word[7:0]) |", "|---|---|---|"]
    rows += [f"| {v} | {k} | {rt['sys_desc'][k]} |" for k, v in rt["enums"]["SYS"].items()]
    t["routine_formats"] = rows
    rows = ["| Op | Name | Argument | Effect |", "|---|---|---|---|"]
    rows += [f"| {c['code']} | {c['name']} | {c['arg']} | {c['desc']} |" for c in s["pin_commands"]]
    t["pin_commands"] = rows
    fab = s["fabric"]
    rows = [f"| Consumer | Legal sources, in `sel` order ({fab['sel_bits']}-bit `sel`) | Count |", "|---|---|---|"]
    rows += [f"| {port} | " + ", ".join(f"{i} {x}" for i, x in enumerate(srcs)) + f" | {len(srcs)} |"
             for port, srcs in legal_sources(fab).items()]
    t["legal_sources"] = rows
    pc = s["pin_config"]
    kinds = {"bool": "0/1", "uint": "value", "m1": "value − 1", "pad": "pad number, 31 = none",
             "q8": "16.8 clocks", "sofs": "16.8 clocks from the bit start"}
    rows = [f"Unit u's block: `{pc['base']:#06x} + u·{pc['stride']:#04x}`; output owners: `{pc['owner_base']:#06x} + (pad − 8)`, "
            "`[2:0]` = unit, 7 = none.", ""]
    feat_units = {k: [u for u, fs in enumerate(pc["units"]) if k in fs] for k in pc["features"]}
    field_feat = {n: k for k, v in pc["features"].items() for n in v["fields"]}
    rows.append("Optional features (D-040); every other field and mode is on all units:")
    for k, us in feat_units.items():
        modes = "; ".join(f"{f.upper()} {', '.join(m)}" for f, m in pc["features"][k]["modes"].items())
        rows.append(f"- **{k}** (units " + ", ".join(f"U{u}" for u in us) + ")"
                    + (f": modes {modes}" if modes else ""))
    store = {"latch": "latch array, no reset (D-038)", "flop": "flops, reset to 0"}[pc["storage"]]
    rows += ["", f"Storage: {store}. Host-readable: {'yes' if pc['readable'] else 'no (D-039)'}.", "",
             "| Word | Bits | Field | Encoding | Units | Meaning |", "|---|---|---|---|---|---|"]
    for f in pc["fields"]:
        w, lsb = divmod(f["bit"], 16)
        hi = lsb + f["width"] - 1
        where = _bits(hi, lsb) if hi < 16 else f"[15:0] + {w + 1}{_bits(hi - 16, 0)}"
        enc = ", ".join(f"{v} {k}" for k, v in f["values"].items()) if f["kind"] == "enum" else kinds[f["kind"]]
        units = "all" if f["name"] not in field_feat else ", ".join(f"U{u}" for u in feat_units[field_feat[f["name"]]])
        rows.append(f"| {w} | {where} | {f['name'].upper()} | {enc} | {units} | {f['desc']} |")
    t["pin_config"] = rows
    return {k: "\n".join(v) for k, v in t.items()}


